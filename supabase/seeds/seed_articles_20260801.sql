## 197款：一个创纪录的数字

2026年7月23日，国家新闻出版署官网发布了本年度第7批游戏审批信息。**197款游戏过审**——其中国产网络游戏193款、进口网络游戏4款，另有8款游戏进行了版号信息变更。这个数字不仅刷新了2026年单月发放纪录，也让2026年累计版号数量达到了1147款。

在所有过审名单中，一个名字格外醒目：**《影之刃零》**。

北京灵游坊网络科技有限公司（S-Game）开发的这款国产3A武侠动作游戏，自首次公开以来就承载着玩家对"后黑神话时代"的无限期待。版号到手，意味着发售进入倒计时。

