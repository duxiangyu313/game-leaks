## 从"暖暖"到"恋与"：女性向之王的崛起

叠纸的发展历程可以概括为三个阶段：

### 第一阶段：换装手游（2012-2017）

《暖暖的换装物语》→《奇迹暖暖》→《闪耀暖暖》，叠纸用"换装"这个细分品类建立了自己的基本盘。核心竞争力是**美术品质**——在同类游戏中，叠纸的服装建模和材质渲染一直是天花板级别。

### 第二阶段：乙女突破（2017-2024）

《恋与制作人》开创了国产乙女游戏品类，随后的《恋与深空》将3D恋爱互动推向了新高度。叠纸从"换装公司"进化为"女性向之王"。

**关键数据**：《恋与深空》在全球范围内取得了商业成功，长期占据App Store畅销榜前列，是叠纸估值的核心支撑。

### 第三阶段：3A转型（2024-至今）

《百面千相》和《无限暖暖》的公布，标志着叠纸试图突破"女性向"标签，进入更广阔的3A游戏市场。

