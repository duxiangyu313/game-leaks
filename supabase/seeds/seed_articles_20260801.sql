## 《恋与深空》争议：250亿估值的裂缝

### "敖尹事件"

2026年6月22日，《恋与深空》空降第六位男主"敖尹"。新角色的设计引发了巨大争议：

- **外观争议**：欧美风狼人外观，与原有五位男主的风格差异显著
- **设定争议**：部分剧情设定被指"不尊重女性"
- **文化失焦**：在国产乙女游戏中植入欧美奇幻元素，被认为偏离了核心用户的文化认同

### 争议背后的深层问题

"敖尹事件"不是简单的新角色翻车，它暴露了叠纸在扩张期的**核心矛盾**：

1. **用户定位撕裂**：核心用户（中国女性玩家）的审美偏好与全球化扩张需求之间的冲突
2. **内容产能压力**：长期运营的恋爱游戏需要持续产出新内容，但"量"的追求可能牺牲"质"
3. **品牌认知固化**：叠纸在女性向领域的成功，反而成为其向其他品类扩张的"认知枷锁"

### 对估值的影响

乙女游戏是叠纸的**现金牛**。如果《恋与深空》的争议导致核心用户流失，将直接影响公司的营收基本盘，进而影响250亿估值的合理性。

