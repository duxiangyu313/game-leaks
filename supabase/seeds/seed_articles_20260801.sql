## 250亿：一个独角兽的诞生

2026年，叠纸游戏（Papergames）首次跻身胡润全球独角兽榜，估值约**250亿人民币**。在中国游戏赛道，叠纸与米哈游并列成为仅有的两家独角兽级游戏公司。

