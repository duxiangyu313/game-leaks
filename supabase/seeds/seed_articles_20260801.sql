## ChinaJoy 2026：AI主题下的国产单机逆袭

### "与AI同游"

本届ChinaJoy以**"与AI同游"**为主题，凸显AI技术在游戏行业的渗透。但展会现场最让玩家排长队的，却是几款国产单机游戏的试玩台：

- **《抵抗者》**：抗战题材FPS，N1馆G201展台，公开试玩版本
- **《仙剑奇侠传四：重制版》**：虚幻5引擎重制，咪咕展台N4-05
- **《一盏秋声：锦衣卫》**：武侠动作，差异化于"翻滚打铁"范式
- **《时空低语》**：国产首款科幻3A单机，融入中华符号
- **《雾影猎人》**：字节跳动旗下魂系新作，7月30日全球发售

这些游戏有一个共同特点：**都不是手游**。在一个传统上以手游和网游为主角的展会上，单机游戏正在抢回聚光灯。

### 为什么单机开始"抢镜"？

- **《黑神话：悟空》效应**：证明了国产单机的商业潜力，资本和人才开始涌入。
- **玩家代际更替**：Z世代玩家对品质的要求更高，对手游的"氪金"模式疲劳。
- **技术民主化**：UE5等引擎降低了3A级别的研发门槛，独立团队也能做出令人惊艳的画面。
- **平台多元化**：PC+主机+云游戏的渠道多元化，让单机游戏有了更多变现路径。

