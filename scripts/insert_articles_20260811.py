def insert_articles():
    if not SERVICE_KEY:
        print("❌ 缺少 SUPABASE_SERVICE_KEY（请确认 .env.local 中存在）")
        return False

    url = f"{SUPABASE_URL}/rest/v1/articles"
    headers = {
        "apikey": SERVICE_KEY,
        "Authorization": f"Bearer {SERVICE_KEY}",
        "Content-Type": "application/json",
        "Prefer": "return=minimal"
    }

    success = 0
    failed = 0

    for i, article in enumerate(ARTICLES):
        # auto-generate UUID and compute word_count/read_time
        article["id"] = str(uuid.uuid4())
        wc = count_words(article.get("content", ""))
        article["word_count"] = wc
        article["read_time"] = max(3, round(wc / 400))  # ~400字/分钟

        body = json.dumps(article, ensure_ascii=False).encode("utf-8")
        req = request.Request(url, data=body, headers=headers, method="POST")
        try:
            with request.urlopen(req, timeout=20) as resp:
                if resp.status in (200, 201, 204):
                    rid = article["id"]
                    print(f"OK  [{i+1}/{len(ARTICLES)}] {article['title'][:48]} | id={rid} | {wc}字")
                    success += 1
                else:
                    print(f"WARN[{i+1}/{len(ARTICLES)}] HTTP {resp.status}: {article['title'][:48]}")
                    failed += 1
        except error.HTTPError as e:
            body_text = e.read().decode("utf-8", errors="replace")
            print(f"ERR [{i+1}/{len(ARTICLES)}] {article['title'][:48]} -> {body_text[:200]}")
            failed += 1
        except Exception as e:
            print(f"ERR [{i+1}/{len(ARTICLES)}] {article['title'][:48]} -> {e}")
            failed += 1

    print("=" * 50)
    print(f"完成: 成功 {success}, 失败 {failed}")
    return failed == 0


