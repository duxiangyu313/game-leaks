def insert_leaks():
    if not SERVICE_KEY:
        print("❌ 缺少 SUPABASE_SERVICE_KEY 环境变量")
        return False

    url = f"{SUPABASE_URL}/rest/v1/leaks"
    headers = {
        "apikey": SERVICE_KEY,
        "Authorization": f"Bearer {SERVICE_KEY}",
        "Content-Type": "application/json",
        "Prefer": "return=minimal"
    }

    success = 0
    failed = 0

    for i, leak in enumerate(LEAKS):
        body = json.dumps(leak, ensure_ascii=False).encode("utf-8")
        req = request.Request(url, data=body, headers=headers, method="POST")
        try:
            with request.urlopen(req, timeout=20) as resp:
                if resp.status in (200, 201, 204):
                    print(f"OK  [{i+1}/{len(LEAKS)}] {leak['title'][:52]}")
                    success += 1
                else:
                    print(f"WARN[{i+1}/{len(LEAKS)}] HTTP {resp.status}: {leak['title'][:52]}")
                    failed += 1
        except error.HTTPError as e:
            body_text = e.read().decode("utf-8", errors="replace")
            print(f"ERR [{i+1}/{len(LEAKS)}] {leak['title'][:52]} -> {body_text[:200]}")
            failed += 1
        except Exception as e:
            print(f"ERR [{i+1}/{len(LEAKS)}] {leak['title'][:52]} -> {e}")
            failed += 1

    print("=" * 50)
    print(f"完成: 成功 {success}, 失败 {failed}")
    return failed == 0


