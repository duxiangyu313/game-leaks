// Word count function for Chinese text
function countWords(text) {
  // Strip markdown syntax
  const plain = text
    .replace(/[#*>\-\|\!\[]/g, '')
    .replace(/\(.*?\)/g, '')
    .replace(/\[.*?\]/g, '')
    .replace(/`/g, '');
  // Count Chinese characters + words
  const chineseChars = (plain.match(/[一-鿿]/g) || []).length;
  const englishWords = (plain.match(/[a-zA-Z]+/g) || []).length;
  return chineseChars + englishWords;
}

function estimateReadTime(wordCount) {
  // Chinese reading speed: ~400 chars/min
  return Math.max(1, Math.ceil(wordCount / 400));
}

async function updateArticle(article) {
  const wc = countWords(article.content);
  const rt = estimateReadTime(wc);
  const excerpt = article.excerpt.trim(); // excerpt already counted in content

  console.log(`Updating: ${article.title}`);
  console.log(`  Word count: ${wc}, Read time: ${rt} min`);

  const { data, error } = await supabase
    .from('articles')
    .update({
      content: article.content,
      excerpt: article.excerpt,
      word_count: wc,
      read_time: rt,
      updated_at: new Date().toISOString()
    })
    .eq('id', article.id)
    .select('id, title, word_count');

  if (error) {
    console.error(`  ERROR: ${error.message}`);
  } else {
    console.log(`  SUCCESS: ${data[0]?.title} → ${data[0]?.word_count} words`);
  }
  return { wc, rt, error };
}

