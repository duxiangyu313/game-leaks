def count_words(md: str) -> int:
    text = re.sub(r"[#*`|\-\[\]()>]", "", md)
    cn = len(re.findall(r"[\u4e00-\u9fff]", text))
    en = len(re.findall(r"[A-Za-z]+", text))
    return cn + en


def insert_articles():
    if not SERVICE_KEY:
        print("缺少 SUPABASE_SERVICE_KEY（请确认 .env.local 中存在）")
        return False

    url = f"{SUPABASE_URL}/rest/v1/articles"
    headers = {
        "apikey": SERVICE_KEY,
        "Authorization": f"Bearer {SERVICE_KEY}",
        "Content-Type": "application/json",
        "Prefer": "return=minimal"
    }

    ok_n = fail_n = 0
    for i, art in enumerate(ARTICLES):
        wc = count_words(art["content"])
        payload = dict(art)
        payload["word_count"] = wc
        payload["read_time"] = max(1, round(wc / 400))
        payload["author_name"] = "国游温度计编辑部"
        payload["published_at"] = "2026-08-08T16:00:00+08:00"

        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        req = request.Request(url, data=body, headers=headers, method="POST")
        try:
            with request.urlopen(req, timeout=25) as resp:
                if resp.status in (200, 201, 204):
                    print(f"OK  [{i+1}/{len(ARTICLES)}] {art['title'][:44]} | {wc}字 / {payload['read_time']}分钟")
                    ok_n += 1
                else:
                    print(f"WARN[{i+1}] HTTP {resp.status}")
                    fail_n += 1
        except error.HTTPError as e:
            print(f"ERR [{i+1}] {art['title'][:40]} -> {e.read().decode('utf-8', 'replace')[:300]}")
            fail_n += 1
        except Exception as e:
            print(f"ERR [{i+1}] {art['title'][:40]} -> {e}")
            fail_n += 1

    print("=" * 50)
    print(f"完成: 成功 {ok_n}, 失败 {fail_n}")
    return fail_n == 0


if __name__ == "__main__":
    sys.exit(0 if insert_articles() else 1)
